"""EXACT-1 milestone E5: the human-readable table data/exact/critical-configs-n12.md, generated from the JSON.

Status: untrusted (exploration or tooling; no part of the completeness proof).

Reads data/exact/critical-configs-n12.json and writes data/exact/critical-configs-n12.md: one summary
table, then one section per configuration (identity, minimal polynomials, intervals, stress cone, motions,
status and provenance).  Gram matrices and stress coordinates stay in the JSON file.
Usage: python3 scripts/exact/table_md.py
"""
import json
import os
import sys

sys.set_int_max_str_digits(0)
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
JS = os.path.join(ROOT, 'data', 'exact', 'critical-configs-n12.json')
MD = os.path.join(ROOT, 'data', 'exact', 'critical-configs-n12.md')

ORDER = ['DOD', 'M', '1.0010073939', '1.0008452029', 'B', 'r1', '1.0003062544', 'A', 'antiprism', 'FCC', 'HCP']
NOT_FOUND = [
    ('1.0003062547', 20, 2, 'no exact data; data/n12_above1.json gives a symmetry group of order 2, but the stored contact graph has only the '
                            'trivial automorphism'),
    ('1.0002374095', 21, 1, 'no exact data'),
    ('1.0002115891', 20, 2, 'no exact data'),
    ('1.0002111636', 19, 3, 'no exact data; high-precision candidate for c of degree 126 (see below)'),
]
R1_NONE = [('r = 1 contact graphs with 15-23 contacts', 'not found, no data (one sentence in the 2026-10-01 note)'),
           ('KKLS M_5 4-simplex stratum at r = 1', 'not found, no data (named in docs/checklist.md C5)')]


def poly_str(co, var='t'):
    """Integer coefficient list (constant first) as a readable polynomial, highest degree first."""
    terms = []
    for k in range(len(co) - 1, -1, -1):
        a = int(co[k])
        if a == 0:
            continue
        mono = '' if k == 0 else (var if k == 1 else '%s^%d' % (var, k))
        coef = str(abs(a)) if (abs(a) != 1 or k == 0) else ''
        terms.append(('-' if a < 0 else '+') + ' ' + coef + mono)
    s = ' '.join(terms)
    return s[2:] if s.startswith('+ ') else '-' + s[2:]


def faces(d):
    """Face sizes as 'n3 tri + n4 quad + ...'."""
    names = {'3': 'tri', '4': 'quad', '5': 'pent', '6': 'hex'}
    return ' + '.join('%d %s' % (v, names.get(k, k + '-gon')) for k, v in d.items())


def main():
    """Write the markdown table."""
    C = json.load(open(JS))['configs']
    L = ['# N = 12 critical configurations found so far: exact data', '',
         'Generated by `scripts/exact/table_md.py` from `data/exact/critical-configs-n12.json` (EXACT-1). '
         'This lists the critical configurations **found so far**; it is not a completeness claim. '
         '"Exactly verified" means an exact computation in K = Q(c) accepted every listed identity and inequality '
         '(scripts and commits per entry below); it is not the completeness checker. Face sizes are numerical. '
         'Conventions: c = cos(theta), s = sin(theta/2), r = s/(1 - s); polynomials are written highest degree '
         'first here and stored constant term first in the JSON. Co-index = directions on the kernel in which r '
         'increases; descending index = directions in which r decreases.', '',
         '| configuration | r (numerical) | contacts | faces | symmetry | deg c | deg r | stress dim | extreme rays | '
         'positive stress | uniform stress | kernel | co-index / desc. index | status |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for lab in ORDER:
        d = C[lab]
        w = d['weights']
        mo = d['motions']
        idx = ('%s / %s' % (mo['coindex'], mo['descending_index'])) if isinstance(mo.get('coindex'), int) else 'degenerate'
        L.append('| %s | %s | %d | %s | %s (%d) | %d | %d | %d | %d | %s | %s | %d | %s | exactly verified |' % (
            lab, d['r_numerical'].split()[0], d['n_contacts'], faces(d['faces']['sizes']), d['symmetry']['name'],
            d['symmetry']['order'], d['c']['degree'], d['r']['degree'], w['dim'], w['n_extreme_rays'],
            'yes' if w['strictly_positive_stress_exists'] else 'no', 'yes' if w['uniform_is_stress'] else 'no',
            mo['kernel_dim_mod_rotations'], idx))
    for lab, k, co, why in NOT_FOUND:
        L.append('| %s | %s | %d | | | not found | | | | | | | %d (numerical) | %s |' % (lab, lab, k, co, why))
    L.append('')
    for lab, why in R1_NONE:
        L.append('- %s: %s.' % (lab, why))
    L.append('')
    for lab, cd in json.load(open(JS)).get('high_precision_candidates', {}).items():
        L.append('- %s: candidate minimal polynomial of c, degree %d, height %d digits, |f(c)| about 10^(%s) at %d '
                 'digits (a chance relation would have height about %d digits); %s; %s. Coefficients in the JSON '
                 'file under "high_precision_candidates".' % (
                     lab, cd['degree'], cd['height_digits'], cd['log10_abs_value_at_c'], cd['digits'],
                     cd['expected_height_digits_of_a_chance_relation'], cd['status'], cd['script']))
    L.append('')
    for lab in ORDER:
        d = C[lab]
        w = d['weights']
        mo = d['motions']
        L += ['## %s' % lab, '',
              '- contacts: %d; canonical edge list `%s`' % (d['n_contacts'], d['canonical_edges']),
              '- symmetry: %s, order %d (rotations %d); contact orbits of sizes %s' % (
                  d['symmetry']['name'], d['symmetry']['order'], d['symmetry']['proper_order'], w['edge_orbit_sizes']),
              '- c: minimal polynomial (degree %d) `%s`; root in [%s, %s]' % (
                  d['c']['degree'], poly_str(d['c']['minpoly']), d['c']['interval'][0], d['c']['interval'][1]),
              '- s^2: `%s`; s: degree %d; r: degree %d, `%s`; r in [%s, %s]' % (
                  poly_str(d['s2']['minpoly'], 'x'), d['s']['degree'], d['r']['degree'],
                  poly_str(d['r']['minpoly'], 'r'), d['r']['interval'][0], d['r']['interval'][1])]
        if 'closed_forms' in d:
            cf = d['closed_forms']
            L.append('- closed forms: c = %s, s = %s, r = %s' % (cf['c'], cf['s'], cf['r']))
        L += ['- Gram matrix: entries in K (JSON); unit diagonal, contacts = c, non-contacts < c, rank 3 and PSD '
              '(frame %s, zero Schur complement)' % d['gram']['checks']['frame'],
              '- weight space: dim %d, balance rank %d; %d extreme ray(s) of the nonnegative cone (supports %s); '
              'strictly positive stress: %s; uniform weight a stress: %s' % (
                  w['dim'], w['balance_rank'], w['n_extreme_rays'],
                  sorted(len(r['support']) for r in w['extreme_rays']),
                  'yes' if w['strictly_positive_stress_exists'] else 'no', 'yes' if w['uniform_is_stress'] else 'no'),
              '- motions: rigidity rank %d, flex dimension %d, kernel %d (mod rotations); co-index %s, descending '
              'index %s' % (mo['rigidity_rank'], mo['flex_dim_mod_rotations'], mo['kernel_dim_mod_rotations'],
                            mo.get('coindex'), mo.get('descending_index', 'n/a')),
              '- status: %s; weights: %s' % (d['status']['script'], w['script'])]
        if d.get('comparisons'):
            L.append('- comparisons: %s' % {k: v for k, v in d['comparisons'].items()})
        L.append('')
    open(MD, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
